"""Generate portable filename collision keys; no runtime Unicode dependency."""
from pathlib import Path
import unicodedata

ROOT = Path(__file__).resolve().parents[1]


def generate():
    rows = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        folded = chr(cp).upper().casefold()
        if folded != chr(cp):
            points = [ord(c) for c in folded]
            assert len(points) <= 3
            rows.append("{%su,{%s}}," % (cp, ",".join(str(v) + "u" for v in points + [0] * (3 - len(points)))))
    return ("/* Generated by tools/generate_extension_casefold.py; Unicode " + unicodedata.unidata_version + ". */\n"
            "#ifndef MDO_EXTENSION_CASEFOLD_H\n#define MDO_EXTENSION_CASEFOLD_H\n"
            "typedef struct MdoExtensionFold {uint32 From,To[3];} MdoExtensionFold;\n"
            "static const MdoExtensionFold MdoExtensionFolds[]={\n" + "\n".join(rows) + "\n};\n#endif\n")


if __name__ == "__main__":
    (ROOT / "app/include/mdo/extension_casefold.h").write_text(generate(), encoding="utf-8")
